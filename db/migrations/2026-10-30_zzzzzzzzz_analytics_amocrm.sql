-- qualification_basis_mappings → an_amo_basis, sync_state / sync_runs →
-- an_amo_sync_state / an_amo_sync_runs, marketing_leads → an_amo_leads (без
-- контактов клиентов: источник, UTM, этапы, основание закрытия),
