-- Их city_aliases.canonical_city: один согласованный псевдоним — Казань
-- Вишневского у Lady Jump.
create or replace function public.an_amo_canonical_city(p_brand text, p_city text)
returns text
language sql
immutable
as $$
  select case
    when btrim(coalesce(p_brand, '')) = 'Lady Jump'
     and btrim(replace(coalesce(p_city, ''), chr(160), ' '), E' \t\n\r')
         in ('Казань', 'Казань Вишневского', 'Казань · Вишневского')
      then 'Казань · Вишневского'
    else p_city
  end
$$;

