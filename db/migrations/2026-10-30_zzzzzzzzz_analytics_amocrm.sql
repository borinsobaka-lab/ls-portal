-- an_amo_snapshot_origins. Их loss_reason_* не используются (причины
-- закрытия amoCRM у них не участвуют) — не переносятся.
--
-- Пишет сервер портала (service_role): сбор сделок — раз в 15 минут (их
-- lady-amocrm-marketing.timer, только чтение amoCRM). Таблицы закрыты
-- браузеру; администратору аналитики — RPC an_amo_*. Реестр таргета
-- получает «Квалификацию VK» (их vk_qualification_metrics): an_vk_register
-- пересоздан.
--
-- Идемпотентно. Выполняет мигратор при старте портала (db/migrate.ts).
-- ============================================================================

-- 1) Таблицы -------------------------------------------------------------------------

create table if not exists public.an_amo_connections (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 160),
  base_url text not null unique check (base_url ~ '^https://[a-z0-9.-]+(:[0-9]+)?$'),
  is_active boolean not null default true,
  last_verified_at timestamptz,
  last_verification_status integer,
  last_verification_details text not null default '',
  token_updated_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.an_amo_metadata (
  connection_id bigint primary key references public.an_amo_connections(id) on delete cascade,
  pipelines jsonb not null default '[]',
  lead_fields jsonb not null default '[]',
  users jsonb not null default '[]',
  fetched_at timestamptz not null default now()
);

create table if not exists public.an_amo_settings (
  connection_id bigint primary key references public.an_amo_connections(id) on delete cascade,
  new_lead_pipeline_id text not null,
  auto_source_field_id text not null,
