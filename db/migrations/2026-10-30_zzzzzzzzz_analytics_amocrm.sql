-- Их _begin_sync: второй запуск того же подключения — не раньше, чем через
-- 30 минут после зависшего.
create or replace function public.an_amo_sync_begin(p_connection bigint, p_mode text)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_state public.an_amo_sync_state;
  v_run bigint;
begin
  insert into public.an_amo_sync_state (connection_id) values (p_connection) on conflict do nothing;
  select * into v_state from public.an_amo_sync_state where connection_id = p_connection for update;
  if v_state.is_running and now() - coalesce(v_state.last_started_at, '-infinity') < interval '30 minutes' then
    raise exception 'Синхронизация этого подключения уже выполняется.' using errcode = 'P0001';
  end if;
  update public.an_amo_sync_state set last_started_at = now(), is_running = true, last_error = ''
   where connection_id = p_connection;
  insert into public.an_amo_sync_runs (connection_id, mode, status) values (p_connection, p_mode, 'running')
  returning id into v_run;
  return v_run;
end;
$$;
revoke all on function public.an_amo_sync_begin(bigint, text) from public, anon, authenticated;
grant execute on function public.an_amo_sync_begin(bigint, text) to service_role;

-- Их _finish_sync: успех двигает «последний успешный» (с него — следующий
-- инкремент), ошибка — остаётся в состоянии.
create or replace function public.an_amo_sync_finish(p_connection bigint, p_run bigint, p_status text,
  p_received integer, p_saved integer, p_details text)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.an_amo_sync_runs
     set finished_at = now(), status = p_status, leads_received = p_received, leads_saved = p_saved,
         details = left(coalesce(p_details, ''), 500)
   where id = p_run;
  update public.an_amo_sync_state
     set last_success_at = case when p_status = 'success' then now() else last_success_at end,
         last_started_at = now(), is_running = false,
         last_error = case when p_status = 'success' then '' else left(coalesce(p_details, ''), 500) end
   where connection_id = p_connection;
end;
$$;
revoke all on function public.an_amo_sync_finish(bigint, bigint, text, integer, integer, text) from public, anon, authenticated;
grant execute on function public.an_amo_sync_finish(bigint, bigint, text, integer, integer, text) to service_role;

-- Их sync_connection, запись пачки: сделку не из воронки новых лидов
-- заводят, только если она уже собрана раньше (перешла в другую воронку);
-- этапы — события (первое обнаружение), версия — при изменении полей среза.
create or replace function public.an_amo_store_leads(p_connection bigint, p_pipeline text, p_rows jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  r jsonb;
  v_saved integer := 0;
  v_other integer := 0;
  v_lead public.an_amo_leads;
  v_payload jsonb;
  v_now timestamptz := now();
begin
  insert into public.an_amo_history_state (id, started_at) values (true, v_now) on conflict (id) do nothing;
  for r in select * from jsonb_array_elements(coalesce(p_rows, '[]')) loop
    if not exists (select 1 from public.an_amo_leads where connection_id = p_connection and amo_lead_id = r->>'amo_lead_id')
       and r->>'pipeline_id' <> p_pipeline then
      v_other := v_other + 1;
      continue;
    end if;
    insert into public.an_amo_leads (connection_id, amo_lead_id, created_at, updated_at, pipeline_id, status_id,
      responsible_user_id, responsible_name, brand, city, partner_name, automatic_source, responsible_source,
      effective_source, utm_source, utm_medium, utm_campaign, utm_content, utm_term, utm_referrer,
      is_booked, is_attended, is_paid, is_closed, close_basis_value_id, close_basis_value, is_qualified,
      first_synced_at, last_synced_at)
    values (p_connection, r->>'amo_lead_id', to_timestamp((r->>'created_at')::bigint),
      to_timestamp((r->>'updated_at')::bigint), r->>'pipeline_id', r->>'status_id', r->>'responsible_user_id',
      r->>'responsible_name', r->>'brand', r->>'city', r->>'partner_name', r->>'automatic_source',
      r->>'responsible_source', r->>'effective_source', r->>'utm_source', r->>'utm_medium', r->>'utm_campaign',
      r->>'utm_content', r->>'utm_term', r->>'utm_referrer', (r->>'is_booked')::smallint,
      (r->>'is_attended')::smallint, (r->>'is_paid')::smallint, (r->>'is_closed')::smallint,
      r->>'close_basis_value_id', r->>'close_basis_value', (r->>'is_qualified')::smallint, v_now, v_now)
    on conflict (connection_id, amo_lead_id) do update set
      updated_at = excluded.updated_at, pipeline_id = excluded.pipeline_id, status_id = excluded.status_id,
      responsible_user_id = excluded.responsible_user_id, responsible_name = excluded.responsible_name,
      brand = excluded.brand, city = excluded.city, partner_name = excluded.partner_name,
      automatic_source = excluded.automatic_source, responsible_source = excluded.responsible_source,
      effective_source = excluded.effective_source, utm_source = excluded.utm_source,
      utm_medium = excluded.utm_medium, utm_campaign = excluded.utm_campaign, utm_content = excluded.utm_content,
      utm_term = excluded.utm_term, utm_referrer = excluded.utm_referrer, is_booked = excluded.is_booked,
      is_attended = excluded.is_attended, is_paid = excluded.is_paid, is_closed = excluded.is_closed,
      close_basis_value_id = excluded.close_basis_value_id, close_basis_value = excluded.close_basis_value,
      is_qualified = excluded.is_qualified, last_synced_at = excluded.last_synced_at
    returning * into v_lead;
    insert into public.an_amo_lead_events (connection_id, amo_lead_id, event_type, detected_at)
    select p_connection, v_lead.amo_lead_id, e.t, v_now
      from (values ('booked', v_lead.is_booked), ('attended', v_lead.is_attended), ('paid', v_lead.is_paid)) e(t, on_)
     where e.on_ = 1
    on conflict do nothing;
    -- Их _record_marketing_version: поля среза; новая версия — только при изменении.
    v_payload := jsonb_build_object(
      'created_at', extract(epoch from v_lead.created_at)::bigint, 'brand', v_lead.brand, 'city', v_lead.city,
      'partner_name', v_lead.partner_name, 'effective_source', v_lead.effective_source,
      'is_qualified', v_lead.is_qualified, 'is_booked', v_lead.is_booked, 'is_attended', v_lead.is_attended,
      'is_paid', v_lead.is_paid);
    if v_payload is distinct from (select v.payload from public.an_amo_versions v
                                     where v.connection_id = p_connection and v.amo_lead_id = v_lead.amo_lead_id
                                     order by v.observed_at desc limit 1) then
      insert into public.an_amo_versions (connection_id, amo_lead_id, observed_at, payload)
      values (p_connection, v_lead.amo_lead_id, v_now, v_payload)
      on conflict (connection_id, amo_lead_id, observed_at) do update set payload = excluded.payload;
    end if;
    v_saved := v_saved + 1;
  end loop;
  return jsonb_build_object('saved', v_saved, 'skipped_other', v_other);
end;
$$;
revoke all on function public.an_amo_store_leads(bigint, text, jsonb) from public, anon, authenticated;
grant execute on function public.an_amo_store_leads(bigint, text, jsonb) to service_role;

-- Их бюджеты среза: расход VK кабинетов бренда за месяц с НДС (×1,22) по
-- городам — лид-формы и сообщения сообщества.
create or replace function public.an_amo_month_budgets(p_brand text, p_from date, p_to date)
returns jsonb
language sql
stable
security definer
set search_path = public
set extra_float_digits = 1
as $$
  select coalesce(jsonb_object_agg(coalesce(b.city, ''), jsonb_build_object(
           'lead_forms', coalesce(b.lead_form_spent, 0) * 1.22::float8,
           'community_messages', greatest(0::float8, coalesce(b.platform_spent, 0) * 1.22::float8
                                                    - coalesce(b.lead_form_spent, 0) * 1.22::float8))), '{}')
    from public.an_vk_register_base(p_from, p_to) b
   where b.brand = p_brand
$$;
revoke all on function public.an_amo_month_budgets(text, date, date) from public, anon, authenticated;

-- Их freeze_due_marketing_snapshots: за каждый закончившийся месяц (МСК) с
-- начала учёта — срез когорты по последним версиям сделок до 1-го числа
-- (+ бюджеты VK месяца). Сентябрь 2026 — разово по текущим данным, если учёт
-- начат позже (их согласованное исключение). Прошлое не выдумывается.
create or replace function public.an_amo_freeze_snapshots()
returns integer
language plpgsql
security definer
set search_path = public
set extra_float_digits = 1
as $$
declare
  v_now timestamptz := now();
  v_started timestamptz;
  v_sep_start timestamptz := timestamptz '2026-09-01 00:00:00 Europe/Moscow';
  v_sep_end timestamptz := timestamptz '2026-10-01 00:00:00 Europe/Moscow';
  v_brand text;
  v_rows jsonb;
  v_cursor timestamp;
  v_boundary timestamp;
  v_start timestamptz;
  v_cutoff timestamptz;
  v_month text;
  v_n integer := 0;
begin
  perform pg_advisory_xact_lock(hashtext('an_amo_snapshots'));
  select started_at into v_started from public.an_amo_history_state where id;
  if v_started is null then
    return 0;
  end if;
  if v_now >= v_sep_end and v_started >= v_sep_end then
    foreach v_brand in array array['Lady Jump', 'Lady Stretch'] loop
      continue when exists (select 1 from public.an_amo_snapshots where brand = v_brand and month = '2026-09');
      select jsonb_agg(to_jsonb(g) order by g.city collate "C", g.partner_name collate "C", g.leads desc,
                       g.source collate "C")
        into v_rows
        from (select coalesce(nullif(l.city, ''), 'Город не сопоставлен') as city,
                     coalesce(nullif(l.partner_name, ''), '—') as partner_name,
                     coalesce(nullif(l.effective_source, ''), 'Не присвоен источник') as source,
                     count(*) as leads, sum(l.is_qualified) as qualified,
                     sum(case when l.is_qualified = 1 and l.is_booked = 1 then 1 else 0 end) as booked,
                     sum(case when l.is_qualified = 1 and l.is_attended = 1 then 1 else 0 end) as attended,
                     sum(case when l.is_qualified = 1 and l.is_paid = 1 then 1 else 0 end) as paid
                from public.an_amo_leads l
               where l.brand = v_brand and l.created_at >= v_sep_start and l.created_at < v_sep_end
               group by 1, 2, 3) g;
      continue when v_rows is null;
      insert into public.an_amo_snapshots (brand, month, cutoff_at, captured_at, rows, budgets)
      values (v_brand, '2026-09', v_sep_end, v_now, v_rows,
              public.an_amo_month_budgets(v_brand, '2026-09-01', '2026-09-30'))
      on conflict do nothing;
      insert into public.an_amo_snapshot_origins (brand, month, actual_fixed_at, reason)
      values (v_brand, '2026-09', v_now, 'User-authorized current-state September baseline, requested 2026-10-05')
      on conflict do nothing;
      v_n := v_n + 1;
    end loop;
  end if;

  v_cursor := date_trunc('month', v_started at time zone 'Europe/Moscow');
  loop
    v_boundary := v_cursor + interval '1 month';
    v_start := v_cursor at time zone 'Europe/Moscow';
    v_cutoff := v_boundary at time zone 'Europe/Moscow';
    exit when v_cutoff > v_now;
    v_month := to_char(v_cursor, 'YYYY-MM');
    foreach v_brand in array array['Lady Jump', 'Lady Stretch'] loop
      continue when exists (select 1 from public.an_amo_snapshots where brand = v_brand and month = v_month);
      with last as (
        select distinct on (v.connection_id, v.amo_lead_id) v.payload as p
          from public.an_amo_versions v
         where v.observed_at < v_cutoff
         order by v.connection_id, v.amo_lead_id, v.observed_at desc
      ), g as (
        select coalesce(nullif(p->>'city', ''), 'Город не сопоставлен') as city,
               coalesce(nullif(p->>'partner_name', ''), '—') as partner_name,
               coalesce(nullif(p->>'effective_source', ''), 'Не присвоен источник') as source,
               count(*) as leads, sum((p->>'is_qualified')::int) as qualified,
               sum(case when (p->>'is_qualified')::int <> 0 and (p->>'is_booked')::int <> 0 then 1 else 0 end) as booked,
               sum(case when (p->>'is_qualified')::int <> 0 and (p->>'is_attended')::int <> 0 then 1 else 0 end) as attended,
               sum(case when (p->>'is_qualified')::int <> 0 and (p->>'is_paid')::int <> 0 then 1 else 0 end) as paid
          from last
         where p->>'brand' = v_brand
           and (p->>'created_at')::bigint >= extract(epoch from v_start)::bigint
           and (p->>'created_at')::bigint < extract(epoch from v_cutoff)::bigint
         group by 1, 2, 3
      )
      select coalesce(jsonb_agg(to_jsonb(g) order by g.city collate "C", g.partner_name collate "C",
                                g.leads desc, g.source collate "C"), '[]')
        into v_rows from g;
      insert into public.an_amo_snapshots (brand, month, cutoff_at, captured_at, rows, budgets)
      values (v_brand, v_month, v_cutoff, v_now, v_rows,
              public.an_amo_month_budgets(v_brand, v_cursor::date, (v_boundary - interval '1 day')::date))
      on conflict do nothing;
      v_n := v_n + 1;
    end loop;
    v_cursor := v_boundary;
  end loop;
  return v_n;
end;
$$;
revoke all on function public.an_amo_freeze_snapshots() from public, anon, authenticated;
