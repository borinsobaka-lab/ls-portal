-- Их import_accounts (файл API_VK_ADS.xlsx, «VK Ads Panel»): без названия,
-- ID или ключа — пропуск; есть кабинет с этим ID — название, ключ,
-- «Активен», пустые город / партнёр / бренд не стирают прежние; новый —
-- бренд Lady Stretch, если не указан. Ключи — шифртекстом от сервера портала.
create or replace function public.an_vk_accounts_import(p_records jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  r jsonb;
  v_name text;
  v_vk text;
  v_cipher text;
  v_city text;
  v_partner text;
  v_brand text;
  v_id bigint;
  v_created integer := 0;
  v_updated integer := 0;
  v_skipped integer := 0;
  v_existing public.an_vk_accounts;
begin
  perform public.an_require_admin();
  if jsonb_typeof(p_records) <> 'array' or jsonb_array_length(p_records) > 5000 then
    raise exception 'Неверный список кабинетов' using errcode = '22023';
  end if;
  for r in select * from jsonb_array_elements(p_records) loop
    v_name := public.an_vk_strip(r->>'name');
    v_vk := public.an_vk_strip(r->>'vk_account_id');
    v_cipher := coalesce(r->>'token_cipher', '');
    if v_name = '' or v_vk = '' or v_cipher = '' or char_length(v_name) > 500 or char_length(v_vk) > 100 then
      v_skipped := v_skipped + 1;
      continue;
    end if;
    v_city := public.an_vk_strip(r->>'city');
    v_partner := public.an_vk_strip(r->>'partner_name');
    v_brand := public.an_vk_strip(r->>'brand');
    if v_brand <> '' and v_brand not in ('Lady Stretch', 'Lady Jump') then
      v_skipped := v_skipped + 1;
      continue;
    end if;
    select * into v_existing from public.an_vk_accounts where vk_account_id = v_vk;
    if found then
      update public.an_vk_accounts
         set name = v_name,
             city = case when v_city = '' then city else left(v_city, 200) end,
             partner_name = case when v_partner = '' then partner_name else left(v_partner, 200) end,
             brand = case when v_brand = '' then brand else v_brand end,
             is_active = true, updated_at = now()
       where id = v_existing.id;
      v_id := v_existing.id;
      v_updated := v_updated + 1;
    else
      insert into public.an_vk_accounts (name, vk_account_id, city, partner_name, brand, is_active)
      values (v_name, v_vk, left(v_city, 200), left(v_partner, 200),
              case when v_brand = '' then 'Lady Stretch' else v_brand end, true)
      returning id into v_id;
      v_created := v_created + 1;
    end if;
    perform public.an_vk_store_token(v_id, v_cipher);
  end loop;
  perform public.an_audit_add(auth.uid(), 'vk_ads_accounts_imported',
    'created=' || v_created || ', updated=' || v_updated || ', skipped=' || v_skipped);
  return jsonb_build_object('created', v_created, 'updated', v_updated, 'skipped', v_skipped);
end;
$$;
revoke all on function public.an_vk_accounts_import(jsonb) from public, anon;
grant execute on function public.an_vk_accounts_import(jsonb) to authenticated;

-- 7) «Расходы по кабинетам» (их control_rows) -----------------------------------------------

-- Расход за день по кабинету: весь и ЛФ (кампании, связанные с лид-формой);
-- суммы — числами с плавающей точкой, как их SUM(CAST(spent AS REAL)).
create or replace function public.an_vk_spend(p_date date)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  perform public.an_require_admin();
  return coalesce((
    select jsonb_agg(jsonb_build_object(
             'account_id', a.id, 'name', a.name, 'vk_account_id', a.vk_account_id, 'city', a.city,
             'partner_name', a.partner_name, 'is_active', a.is_active,
             'platform_spent', coalesce(s.platform_spent, 0), 'lead_form_spent', coalesce(s.lead_form_spent, 0),
             'updated_at', s.updated_at, 'campaign_rows', coalesce(s.campaign_rows, 0))
           order by a.city collate "C", a.name collate "C", a.id)
      from public.an_vk_accounts a
      left join lateral (
        select sum(d.spent::float8) as platform_spent,
               sum(case when exists (select 1 from public.an_vk_lead_form_links l
                                       where l.account_id = d.account_id and l.vk_plan_id = d.vk_plan_id)
                        then d.spent::float8 else 0 end) as lead_form_spent,
               max(d.updated_at) as updated_at, count(d.vk_plan_id) as campaign_rows
          from public.an_vk_daily_stats d
         where d.account_id = a.id and d.stat_date = p_date) s on true), '[]');
end;
$$;
revoke all on function public.an_vk_spend(date) from public, anon;
grant execute on function public.an_vk_spend(date) to authenticated;
