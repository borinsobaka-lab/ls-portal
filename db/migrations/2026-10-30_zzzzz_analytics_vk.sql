-- «Аналитика» → VK Ads, часть 1 (ANALYTICS.md, «VK Ads»; ANALYTICS_PLAN.md,
-- §8.4): рекламные кабинеты, сбор из API VK Ads (остатки, кампании, дневная
-- статистика, лид-формы и их связи с кампаниями), «Расходы по кабинетам».
--
-- Их vk_ads.py: ad_accounts / account_credentials / sync_runs /
-- raw_api_responses / account_balances / ad_plans / daily_campaign_statistics /
-- lead_forms / lead_form_campaign_links → an_vk_*. API-ключ кабинета — в
-- an_secrets (kind 'vk_ads', ref — id кабинета, name 'token'; шифрует сервер
-- портала, ANALYTICS_SECRETS_KEY), сюда приходит уже шифртекст. Со старым
-- порталом не связано: кабинеты и ключи заводятся заново (вручную или
-- импортом их Excel API_VK_ADS.xlsx).
--
-- Пишет сбор — сервер портала (service_role), раз в час (их
-- lady-vk-ads.timer, OnCalendar=hourly). Таблицы закрыты браузеру, страницы
-- читают и меняют кабинеты через RPC администратора аналитики.
--
-- Идемпотентно. Выполняет мигратор при старте портала (db/migrate.ts).
-- ============================================================================

-- 1) Кабинеты -------------------------------------------------------------------------

create table if not exists public.an_vk_accounts (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 500),
  vk_account_id text not null unique check (char_length(vk_account_id) between 1 and 100),
  city text not null default '' check (char_length(city) <= 200),
  brand text not null default 'Lady Stretch' check (brand in ('Lady Stretch', 'Lady Jump')),
  partner_name text not null default '' check (char_length(partner_name) <= 200),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  -- Их account_credentials: проверка ключа последним сбором (200 — ключ
  -- проверен, иначе код ошибки; null — не проверялся).
  last_verified_at timestamptz,
  last_verification_status integer
);

-- Удалённый кабинет — и его ключ (у них ON DELETE CASCADE account_credentials).
create or replace function public.an_vk_accounts_secret_ad()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  delete from public.an_secrets where kind = 'vk_ads' and ref = old.id::text;
  return old;
end;
$$;
revoke all on function public.an_vk_accounts_secret_ad() from public, anon, authenticated;
drop trigger if exists an_vk_accounts_secret_ad on public.an_vk_accounts;
create trigger an_vk_accounts_secret_ad after delete on public.an_vk_accounts
  for each row execute function public.an_vk_accounts_secret_ad();

