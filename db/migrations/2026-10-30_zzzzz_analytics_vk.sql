-- 5) Правила их кода -----------------------------------------------------------------------

-- Их city_aliases.canonical_city: одна согласованная замена — Казань Lady
-- Jump (бренд-специфично, без глобальной замены Казани).
create or replace function public.an_vk_canonical_city(p_brand text, p_city text)
returns text
language sql
immutable
parallel safe
as $$
  select case
    when btrim(coalesce(p_brand, '')) = 'Lady Jump'
     and btrim(replace(coalesce(p_city, ''), chr(160), ' ')) in ('Казань', 'Казань Вишневского', 'Казань · Вишневского')
    then 'Казань · Вишневского'
    else p_city
  end
$$;

-- Их str.strip() для полей формы.
create or replace function public.an_vk_strip(p text)
returns text
language sql
immutable
parallel safe
as $$
  select public.an_rv_strip(p)
$$;

create or replace function public.an_vk_check_brand(p_brand text)
returns text
language plpgsql
immutable
as $$
begin
  if public.an_vk_strip(p_brand) not in ('Lady Stretch', 'Lady Jump') then
    raise exception 'Выберите допустимый бренд.' using errcode = '22023';
  end if;
  return public.an_vk_strip(p_brand);
end;
$$;

-- Шифртекст ключа от сервера портала: base64(iv ‖ данные ‖ тег).
create or replace function public.an_vk_store_token(p_account bigint, p_cipher text)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if coalesce(p_cipher, '') !~ '^[A-Za-z0-9+/]{40,}={0,2}$' then
    raise exception 'Ключ не зашифрован — сохраните его через портал.' using errcode = '22023';
  end if;
  insert into public.an_secrets (kind, ref, name, ciphertext, updated_at, updated_by)
  values ('vk_ads', p_account::text, 'token', p_cipher, now(), auth.uid())
  on conflict (kind, ref, name) do update
    set ciphertext = excluded.ciphertext, updated_at = excluded.updated_at, updated_by = excluded.updated_by;
end;
$$;
revoke all on function public.an_vk_store_token(bigint, text) from public, anon, authenticated;

-- 6) «Рекламные кабинеты» (администратору аналитики) ------------------------------------

-- Их list_accounts + города (1С) и партнёры для выбора.
create or replace function public.an_vk_accounts()
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  perform public.an_require_admin();
  return jsonb_build_object(
    'accounts', coalesce((
      select jsonb_agg(jsonb_build_object(
               'id', a.id, 'name', a.name, 'vk_account_id', a.vk_account_id, 'city', a.city,
               'brand', a.brand, 'partner_name', a.partner_name, 'is_active', a.is_active,
               'last_verified_at', a.last_verified_at,
               'last_verification_status', a.last_verification_status,
               'last_balance_at', b.measured_at, 'last_balance', b.balance::text)
             order by a.brand collate "C", a.city collate "C", a.name collate "C", a.id)
        from public.an_vk_accounts a
        left join lateral (
          select measured_at, balance from public.an_vk_balances x
           where x.account_id = a.id order by x.measured_at desc, x.id desc limit 1) b on true), '[]'),
    'cities', to_jsonb(public.an_partner_city_options()),
    'partners', coalesce((
      select jsonb_agg(n order by n collate "C")
        from (select distinct coalesce(nullif(btrim(p.full_name), ''), u.email::text, '') as n
                from (select distinct user_id from public.an_partner_cities) c
                join auth.users u on u.id = c.user_id
                left join public.profiles p on p.id = c.user_id) x
       where n <> ''), '[]'));
end;
$$;
revoke all on function public.an_vk_accounts() from public, anon;
grant execute on function public.an_vk_accounts() to authenticated;

-- Их save_account (новый кабинет): название, ID VK Ads, город, ключ — обязательны.
create or replace function public.an_vk_account_create(
  p_name text, p_vk_account_id text, p_city text, p_partner_name text, p_brand text, p_token_cipher text)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_brand text;
  v_city text;
  v_id bigint;
begin
  perform public.an_require_admin();
  v_city := public.an_vk_strip(public.an_vk_canonical_city(p_brand, p_city));
  if public.an_vk_strip(p_name) = '' or public.an_vk_strip(p_vk_account_id) = '' or v_city = ''
     or coalesce(p_token_cipher, '') = '' then
    raise exception 'Название, ID VK Ads, город и API-ключ обязательны.' using errcode = '22023';
  end if;
  v_brand := public.an_vk_check_brand(p_brand);
  if exists (select 1 from public.an_vk_accounts where vk_account_id = public.an_vk_strip(p_vk_account_id)) then
    raise exception 'Кабинет с таким ID VK Ads уже есть.' using errcode = '23505';
  end if;
  insert into public.an_vk_accounts (name, vk_account_id, city, partner_name, brand)
  values (public.an_vk_strip(p_name), public.an_vk_strip(p_vk_account_id), v_city,
          public.an_vk_strip(p_partner_name), v_brand)
  returning id into v_id;
  perform public.an_vk_store_token(v_id, p_token_cipher);
  perform public.an_audit_add(auth.uid(), 'vk_ads_account_created', v_id::text);
  return v_id;
end;
$$;
revoke all on function public.an_vk_account_create(text, text, text, text, text, text) from public, anon;
grant execute on function public.an_vk_account_create(text, text, text, text, text, text) to authenticated;

