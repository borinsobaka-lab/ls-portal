-- 6) Реестр таргета ---------------------------------------------------------------------

-- Их target_register_rows без фильтра таргетолога: по бренду и городу за
-- период — расход платформы и ЛФ (кампании, связанные с лид-формой), лиды и
-- заявки СС, заявки ЛФ, активные кабинеты, назначенный таргетолог.
create or replace function public.an_vk_register_base(p_from date, p_to date)
returns table (brand text, city text, platform_spent double precision, lead_form_spent double precision,
  campaign_rows bigint, accounts_count bigint, community_leads bigint, community_applications bigint,
  lead_form_applications bigint, targetologist_name text)
language sql
stable
security definer
set search_path = public
as $$
  with community as (
    select m.brand, m.city, sum(m.leads_count) as leads_count, sum(m.applications_count) as applications_count
      from public.an_vk_ss_daily m
     where m.stat_date between p_from and p_to
     group by m.brand, m.city
  ), lead_form_apps as (
    select a.brand, a.city, sum(m.applications_count) as applications_count
      from public.an_vk_lf_daily m
      join public.an_vk_accounts a on a.id = m.account_id
     where m.stat_date between p_from and p_to
     group by a.brand, a.city
  ), stats as (
    select a.brand, a.city,
           sum(s.spent::float8) as platform_spent,
           sum(case when exists (select 1 from public.an_vk_lead_form_links l
                                  where l.account_id = s.account_id and l.vk_plan_id = s.vk_plan_id)
                    then s.spent::float8 else 0 end) as lead_form_spent,
           count(distinct s.vk_plan_id) as campaign_rows
      from public.an_vk_daily_stats s
      join public.an_vk_accounts a on a.id = s.account_id
     where s.stat_date between p_from and p_to
     group by a.brand, a.city
  ), cities as (
    select st.brand, st.city from stats st
    union select c.brand, c.city from community c
    union select l.brand, l.city from lead_form_apps l
  ), city_accounts as (
    select a.brand, a.city, count(distinct a.id) as accounts_count
      from public.an_vk_accounts a where a.is_active group by a.brand, a.city
  )
  select c.brand, c.city,
         coalesce(st.platform_spent, 0), coalesce(st.lead_form_spent, 0), coalesce(st.campaign_rows, 0),
         coalesce(ca.accounts_count, 0), coalesce(cm.leads_count, 0), coalesce(cm.applications_count, 0),
         coalesce(lf.applications_count, 0), t.targetologist_name
    from cities c
    left join stats st on st.brand = c.brand and st.city = c.city
    left join city_accounts ca on ca.brand = c.brand and ca.city = c.city
    left join community cm on cm.brand = c.brand and cm.city = c.city
    left join lead_form_apps lf on lf.brand = c.brand and lf.city = c.city
    left join public.an_vk_targetologists t on t.brand = c.brand and t.city = c.city
$$;
revoke all on function public.an_vk_register_base(date, date) from public, anon, authenticated;

-- Их budget_outage_days (правило 12.10): по активным кабинетам бренда и
-- города, по дням МСК до вчера. Дневной бюджет — исходный план месяца ×
-- целевой CPL / дни месяца, сравнения — перекрёстным умножением в numeric
-- (их Decimal). Без плана или без снимков всех кабинетов — прежнее правило:
-- простой, если не было ни положительного остатка, ни расхода; такие дни без
-- полной истории (не все кабинеты со снимком или меньше 24 часов снимков) —
-- «Без истории». Исключение «Lady Stretch · Владимир, 07.10.2026» — их.
create or replace function public.an_vk_outage_days(p_from date, p_to date, p_keys jsonb, p_today date)
returns table (brand text, city text, zero_days date[], assumed_days date[])
language sql
stable
security definer
set search_path = public
set extra_float_digits = 1
as $$
  with keys as (
    select distinct k->>'brand' as brand, k->>'city' as city
      from jsonb_array_elements(coalesce(p_keys, '[]')) k
  ), bounds as (
    select p_from as d0, least(p_to, p_today - 1) as d1
  ), days as (
    select g::date as day from bounds, generate_series(bounds.d0, bounds.d1, interval '1 day') g
  ), acc as (
    select a.id, a.brand, a.city, a.created_at
      from public.an_vk_accounts a join keys k on k.brand = a.brand and k.city = a.city
     where a.is_active
  ), snap as (
    select b.account_id, (b.measured_at at time zone 'Europe/Moscow')::date as day,
           (array_agg(b.balance order by b.measured_at, b.id))[1] as opening,
           (array_agg(b.balance order by b.measured_at desc, b.id desc))[1] as closing,
           count(distinct extract(hour from b.measured_at at time zone 'Europe/Moscow')) as hours,
           bool_or(b.balance > 0) as positive
      from public.an_vk_balances b
      join acc on acc.id = b.account_id
      cross join bounds
     where b.measured_at >= (bounds.d0::timestamp at time zone 'Europe/Moscow')
       and b.measured_at < ((bounds.d1 + 1)::timestamp at time zone 'Europe/Moscow')
       and b.balance not in ('NaN'::numeric, 'Infinity'::numeric, '-Infinity'::numeric)
     group by 1, 2
  ), spend as (
    select s.account_id, s.stat_date as day, sum(s.spent) as spent
      from public.an_vk_daily_stats s
      join acc on acc.id = s.account_id
      cross join bounds
     where s.stat_date between bounds.d0 and bounds.d1
       and s.spent not in ('NaN'::numeric, 'Infinity'::numeric, '-Infinity'::numeric)
     group by 1, 2
  ), plans as (
    select p.month, p.brand, p.city, p.applications_plan::numeric * (p.target_cpl::text)::numeric as budget
      from public.an_vk_plans p join keys k on k.brand = p.brand and k.city = p.city
  ), per_day as (
    select k.brand, k.city, d.day,
           count(acc.id) as members,
           count(sn.account_id) as with_snap,
           coalesce(sum(sp.spent), 0) as spent,
           coalesce(sum(sn.opening), 0) as opening,
           coalesce(sum(sn.closing), 0) as closing,
           coalesce(bool_or(coalesce(sn.positive, false) or coalesce(sp.spent, 0) > 0), false) as active,
           coalesce(bool_or(sn.hours < 24), false) as short_history
      from keys k
      cross join days d
      left join acc on acc.brand = k.brand and acc.city = k.city
                   and acc.created_at < ((d.day + 1)::timestamp at time zone 'Europe/Moscow')
      left join snap sn on sn.account_id = acc.id and sn.day = d.day
      left join spend sp on sp.account_id = acc.id and sp.day = d.day
     where not (k.brand = 'Lady Stretch' and k.city = 'Владимир' and d.day = date '2026-10-07')
     group by k.brand, k.city, d.day
  ), judged as (
    select pd.*, pl.budget,
           extract(day from (date_trunc('month', pd.day) + interval '1 month - 1 day'))::int as month_days,
           coalesce(pl.budget > 0, false) and pd.members > 0 and pd.with_snap = pd.members as planned,
           pd.members > 0 and pd.with_snap = pd.members as complete
      from per_day pd
      left join plans pl on pl.month = to_char(pd.day, 'YYYY-MM') and pl.brand = pd.brand and pl.city = pd.city
  ), verdict as (
    select j.brand, j.city, j.day, j.planned, j.complete, j.short_history,
           case when j.planned then
             case when j.opening * j.month_days > j.budget and j.closing * j.month_days > j.budget then false
                  when j.spent * j.month_days * 2 >= j.budget then false
                  when j.closing * j.month_days > j.budget then true
                  else j.opening * j.month_days * 2 < j.budget end
           else not j.active end as outage
      from judged j
  )
  select k.brand, k.city,
         coalesce(array_agg(v.day order by v.day) filter (where v.outage), '{}'),
         coalesce(array_agg(v.day order by v.day)
                    filter (where v.outage and not v.planned and (not v.complete or v.short_history)), '{}')
    from keys k
    left join verdict v on v.brand = k.brand and v.city = k.city
   group by k.brand, k.city
$$;
revoke all on function public.an_vk_outage_days(date, date, jsonb, date) from public, anon, authenticated;

-- Реестр таргета: администратору аналитики — все таргетологи (выбор по
-- ФИО), таргетологу — только его города, сотруднику с правом на реестр —
-- все (их /dashboards/target_register: фильтр — из адреса). Строки — города
-- с данными за период и города с планом на месяцы периода; к ним — планы,
-- факт месяца до начала периода (для плана по остатку) и дни без бюджета.
-- Просмотр не администратором — «открыл дашборд» в журнале (как их GET).
create or replace function public.an_vk_register(p_from text, p_to text, p_targetologist text, p_brand text)
returns jsonb
language plpgsql
security definer
set search_path = public
set jit = off
set extra_float_digits = 1
as $$
declare
  v_me jsonb := public.an_me_for(auth.uid());
  v_admin boolean;
  v_forced boolean;
  v_target text;
  v_brand text;
  v_from date;
  v_to date;
  v_swap date;
  v_today date := (now() at time zone 'Europe/Moscow')::date;
  v_first date;
  v_cutoff date;
  v_rows jsonb;
  v_keys jsonb;
  v_facts jsonb := '[]';
begin
  if v_me is null or not (coalesce((v_me->>'admin')::boolean, false)
                          or coalesce(v_me->'reports', '[]') ? 'vk.register') then
    raise exception 'an_forbidden' using errcode = '42501';
  end if;
  if coalesce(p_from, '') !~ '^\d{4}-\d{2}-\d{2}$' or coalesce(p_to, '') !~ '^\d{4}-\d{2}-\d{2}$' then
    raise exception 'Неверный период' using errcode = '22023';
  end if;
  v_from := p_from::date;
  v_to := p_to::date;
  if v_to < v_from then
    v_swap := v_from; v_from := v_to; v_to := v_swap;
  end if;
  if v_to - v_from > 400 then
    raise exception 'Слишком длинный период' using errcode = '22023';
  end if;
  v_admin := coalesce((v_me->>'admin')::boolean, false);
  v_forced := v_me->>'targetologist' is not null;
  v_target := case when v_forced then v_me->>'targetologist' else public.an_vk_strip(p_targetologist) end;
  v_brand := case when p_brand in ('Lady Stretch', 'Lady Jump') then p_brand else '' end;

  if not v_admin then
    perform public.an_audit_add(auth.uid(), 'dashboard_view', 'Реестр таргета');
  end if;

  -- Таргетолог без ФИО в профиле не видит ничего (у них ФИО было всегда).
  with base as (
    select b.* from public.an_vk_register_base(v_from, v_to) b
     where not (v_forced and v_target = '')
       and (v_target = '' or b.targetologist_name = v_target)
       and (v_brand = '' or b.brand = v_brand)
  ), months as (
    select to_char(g, 'YYYY-MM') as month
      from generate_series(date_trunc('month', v_from), v_to, interval '1 month') g
  ), planned as (
    select distinct p.brand, p.city, t.targetologist_name
      from public.an_vk_plans p
      join months m on m.month = p.month
      left join public.an_vk_targetologists t on t.brand = p.brand and t.city = p.city
     where not (v_forced and v_target = '')
       and (v_brand = '' or p.brand = v_brand)
       and (v_target = '' or coalesce(t.targetologist_name, '') = v_target)
       and not exists (select 1 from base b where b.brand = p.brand and b.city = p.city)
  ), all_rows as (
    select b.brand, b.city, b.platform_spent, b.lead_form_spent, b.campaign_rows, b.accounts_count,
           b.community_leads, b.community_applications, b.lead_form_applications, b.targetologist_name
      from base b
    union all
    select p.brand, p.city, 0, 0, 0, 0, 0, 0, 0, p.targetologist_name from planned p
  )
  select coalesce(jsonb_agg(to_jsonb(r)), '[]') into v_rows from all_rows r;

  select coalesce(jsonb_agg(jsonb_build_object('brand', r->>'brand', 'city', r->>'city')), '[]')
    into v_keys from jsonb_array_elements(v_rows) r;

  -- Факт месяца до начала периода: у первого месяца, если период начат не
  -- с 1-го (будущий период — факт по сегодня).
  v_first := date_trunc('month', v_from)::date;
  v_cutoff := least(v_from - 1, v_today);
  if v_cutoff >= v_first then
    select coalesce(jsonb_agg(jsonb_build_object(
             'month', to_char(v_first, 'YYYY-MM'), 'brand', b.brand, 'city', b.city,
             'applications', b.community_applications + b.lead_form_applications)), '[]')
      into v_facts
      from public.an_vk_register_base(v_first, v_cutoff) b
      join jsonb_array_elements(v_keys) k on k->>'brand' = b.brand and k->>'city' = b.city;
  end if;

  return jsonb_build_object(
    'from', v_from, 'to', v_to, 'today', v_today,
    'admin', v_admin,
    'targetologist', v_target,
    'brand', v_brand,
    'people', case when v_admin then to_jsonb(public.an_vk_targetologist_people()) else '[]'::jsonb end,
    'rows', (
      select coalesce(jsonb_agg(r || jsonb_build_object(
               'zero_days', to_jsonb(coalesce(o.zero_days, '{}')),
               'assumed_days', to_jsonb(coalesce(o.assumed_days, '{}')))), '[]')
        from jsonb_array_elements(v_rows) r
        left join public.an_vk_outage_days(v_from, v_to, v_keys, v_today) o
          on o.brand = r->>'brand' and o.city = r->>'city'),
    'plans', coalesce((
      select jsonb_agg(jsonb_build_object(
               'month', p.month, 'brand', p.brand, 'city', p.city,
               'applications_plan', p.applications_plan, 'target_cpl', p.target_cpl)
             order by p.month, public.an_vk_nocase(p.brand), public.an_vk_nocase(p.city))
        from public.an_vk_plans p
        join (select distinct to_char(g, 'YYYY-MM') as month
                from generate_series(date_trunc('month', v_from), v_to, interval '1 month') g) m
          on m.month = p.month
        join jsonb_array_elements(v_keys) k on k->>'brand' = p.brand and k->>'city' = p.city), '[]'),
    'facts', v_facts);
end;
$$;
revoke all on function public.an_vk_register(text, text, text, text) from public, anon;
grant execute on function public.an_vk_register(text, text, text, text) to authenticated;
