  values (v_brand, v_city, v_name, now())
  on conflict (brand, city) do update
    set targetologist_name = excluded.targetologist_name, updated_at = excluded.updated_at;
  perform public.an_audit_add(auth.uid(), 'city_targetologist_saved',
    format('%s: %s', coalesce(p_brand, ''), coalesce(p_city, '')));
