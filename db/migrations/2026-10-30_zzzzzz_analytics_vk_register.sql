-- 1) Таблицы -------------------------------------------------------------------------

create table if not exists public.an_vk_plans (
  month text not null check (month ~ '^\d{4}-(0[1-9]|1[0-2])$'),
  brand text not null check (brand in ('Lady Stretch', 'Lady Jump')),
  city text not null check (char_length(city) between 1 and 200),
  applications_plan integer not null check (applications_plan >= 0),
  -- Их REAL: целевая цена заявки — число с плавающей точкой.
  target_cpl double precision not null check (target_cpl > 0 and target_cpl < 'Infinity'),
  updated_at timestamptz not null default now(),
  primary key (month, brand, city)
);

create table if not exists public.an_vk_plan_changes (
  id bigint generated by default as identity primary key,
  month text not null,
  brand text not null,
  city text not null,
  previous_applications_plan integer,
  previous_target_cpl double precision,
  applications_plan integer not null,
  target_cpl double precision not null,
  changed_by text not null default '',
  changed_by_id uuid references auth.users(id) on delete set null,
  changed_at timestamptz not null default now()
);
create index if not exists an_vk_plan_changes_month on public.an_vk_plan_changes (month, changed_at desc, id desc);

create table if not exists public.an_vk_targetologists (
  brand text not null check (brand in ('Lady Stretch', 'Lady Jump')),
  city text not null check (char_length(city) between 1 and 200),
  targetologist_name text not null check (char_length(targetologist_name) between 1 and 300),
  updated_at timestamptz not null default now(),
  primary key (brand, city)
);

create table if not exists public.an_vk_ss_sources (
  brand text not null check (brand in ('Lady Stretch', 'Lady Jump')),
  city text not null check (char_length(city) between 1 and 120),
  leads_sheet_url text not null check (char_length(leads_sheet_url) <= 2000),
  applications_sheet_url text not null check (char_length(applications_sheet_url) <= 2000),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (brand, city)
);

create table if not exists public.an_vk_ss_daily (
  brand text not null,
  city text not null,
  stat_date date not null,
  leads_count integer not null default 0,
  applications_count integer not null default 0,
  updated_at timestamptz not null default now(),
  primary key (brand, city, stat_date)
);
create index if not exists an_vk_ss_daily_date on public.an_vk_ss_daily (stat_date, brand, city);

create table if not exists public.an_vk_lf_daily (
  account_id bigint not null references public.an_vk_accounts(id) on delete cascade,
  stat_date date not null,
  applications_count integer not null default 0,
  updated_at timestamptz not null default now(),
  primary key (account_id, stat_date)
);
create index if not exists an_vk_lf_daily_date on public.an_vk_lf_daily (stat_date, account_id);

-- Подключение Google (почта сервисного аккаунта — чтобы дать ему доступ к
-- таблицам; сам ключ — в an_secrets).
create table if not exists public.an_google_settings (
  id boolean primary key default true check (id),
  sa_client_email text not null default '',
  sa_updated_at timestamptz,
  sa_updated_by uuid references auth.users(id) on delete set null
);

