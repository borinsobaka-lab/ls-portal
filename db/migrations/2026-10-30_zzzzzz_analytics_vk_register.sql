-- COLLATE NOCASE SQLite: без регистра только латиница A–Z, остальное — по кодам.
create or replace function public.an_vk_nocase(p text)
returns text
language sql
immutable
parallel safe
as $$
  select translate(p, 'ABCDEFGHIJKLMNOPQRSTUVWXYZ', 'abcdefghijklmnopqrstuvwxyz') collate "C"
$$;

-- Города кабинетов (их datalist: sorted по кодам, без пустых).
create or replace function public.an_vk_account_cities()
returns text[]
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(array_agg(c order by c collate "C"), '{}')
    from (select distinct public.an_vk_strip(city) as c from public.an_vk_accounts) x
   where c <> ''
$$;
revoke all on function public.an_vk_account_cities() from public, anon, authenticated;

-- Их targetologist_users(): действующие люди портала с правом таргетолога
-- (администратор аналитики таргетологом не считается — an_me_for), по ФИО.
create or replace function public.an_vk_targetologist_people()
returns text[]
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(array_agg(n order by public.an_vk_nocase(n), n collate "C"), '{}')
    from (select distinct btrim(p.full_name) as n
            from public.access_user_rights r
            join public.profiles p on p.id = r.user_id
           where r.portal
             and 'an.targetologist' = any (r.rights)
             and not ('an.admin' = any (r.rights) or 'portal.admin' = any (r.rights))
             and btrim(coalesce(p.full_name, '')) <> '') x
$$;
revoke all on function public.an_vk_targetologist_people() from public, anon, authenticated;

-- 3) Планы таргета (администратору аналитики) -------------------------------------------

-- Их monthly_plans + monthly_plan_changes (последние 100) + города для
-- ручного плана (кабинеты и планы месяца).
create or replace function public.an_vk_plans_month(p_month text)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
set extra_float_digits = 1
as $$
begin
  perform public.an_require_admin();
  return jsonb_build_object(
    'plans', coalesce((
      select jsonb_agg(jsonb_build_object(
               'month', p.month, 'brand', p.brand, 'city', p.city,
               'applications_plan', p.applications_plan, 'target_cpl', p.target_cpl)
             order by public.an_vk_nocase(p.brand), public.an_vk_nocase(p.city))
        from public.an_vk_plans p where p.month = p_month), '[]'),
    'changes', coalesce((
      select jsonb_agg(jsonb_build_object(
               'brand', c.brand, 'city', c.city,
               'previous_applications_plan', c.previous_applications_plan,
               'previous_target_cpl', c.previous_target_cpl,
               'applications_plan', c.applications_plan, 'target_cpl', c.target_cpl,
               'changed_by', c.changed_by, 'changed_at', c.changed_at)
             order by c.changed_at desc, c.id desc)
        from (select * from public.an_vk_plan_changes x where x.month = p_month
               order by x.changed_at desc, x.id desc limit 100) c), '[]'),
    'cities', coalesce((
      select jsonb_agg(c order by c collate "C")
        from (select unnest(public.an_vk_account_cities()) as c
              union select city from public.an_vk_plans where month = p_month) x), '[]'));
end;
$$;
revoke all on function public.an_vk_plans_month(text) from public, anon;
grant execute on function public.an_vk_plans_month(text) to authenticated;

-- Их save_monthly_plans: проверки по порядку, без изменений — не пишет, иначе
-- план и строка истории (кто — ФИО из профиля). Возвращает число изменённых.
create or replace function public.an_vk_plans_save_month(
  p_month text, p_brand text, p_plans jsonb, p_user uuid)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_month text := btrim(coalesce(p_month, ''));
  v_brand text;
  v_seen text[] := '{}';
  v_cities text[] := '{}';
  v_apps integer[] := '{}';
  v_cpls double precision[] := '{}';
  v_by text;
  e jsonb;
  v_city text;
  v_num numeric;
  v_prev public.an_vk_plans;
  v_had boolean;
  v_changed integer := 0;
  i integer;
begin
  if v_month !~ '^\d{4}-(0[1-9]|1[0-2])$' then
    raise exception 'Укажите месяц в формате ГГГГ-ММ.' using errcode = '22023';
  end if;
  v_brand := public.an_vk_check_brand(p_brand);
  if p_plans is null or jsonb_typeof(p_plans) <> 'array' or jsonb_array_length(p_plans) = 0 then
    raise exception 'В файле не найдено ни одного заполненного плана.' using errcode = '22023';
  end if;
  if jsonb_array_length(p_plans) > 2000 then
    raise exception 'Слишком много строк плана.' using errcode = '22023';
  end if;
  for e in select * from jsonb_array_elements(p_plans) loop
    v_city := public.an_vk_strip(public.an_vk_canonical_city(p_brand, e->>'city'));
    if v_city = '' or v_city = any (v_seen) then
      raise exception 'Город «%» повторяется в файле.', coalesce(nullif(v_city, ''), 'без названия')
        using errcode = '22023';
    end if;
    if jsonb_typeof(e->'applications_plan') is distinct from 'number' then
      raise exception 'План заявок для «%» должен быть целым числом от нуля.', v_city using errcode = '22023';
    end if;
    v_num := (e->>'applications_plan')::numeric;
    if v_num < 0 or v_num <> trunc(v_num) or v_num > 2000000000 then
      raise exception 'План заявок для «%» должен быть целым числом от нуля.', v_city using errcode = '22023';
    end if;
    if jsonb_typeof(e->'target_cpl') is distinct from 'number' or (e->>'target_cpl')::numeric <= 0
       or (e->>'target_cpl')::numeric > 1e15 then
      raise exception 'Стоимость заявки для «%» должна быть числом больше нуля.', v_city using errcode = '22023';
    end if;
    v_seen := v_seen || v_city;
    v_cities := v_cities || v_city;
    v_apps := v_apps || v_num::integer;
    v_cpls := v_cpls || (e->>'target_cpl')::double precision;
  end loop;

  select left(btrim(coalesce(full_name, '')), 160) into v_by from public.profiles where id = p_user;
  for i in 1 .. cardinality(v_cities) loop
    select * into v_prev from public.an_vk_plans
     where month = v_month and brand = v_brand and city = v_cities[i];
    v_had := found;
    if v_had and v_prev.applications_plan = v_apps[i] and v_prev.target_cpl = v_cpls[i] then
      continue;
    end if;
    insert into public.an_vk_plans (month, brand, city, applications_plan, target_cpl, updated_at)
    values (v_month, v_brand, v_cities[i], v_apps[i], v_cpls[i], now())
    on conflict (month, brand, city) do update
      set applications_plan = excluded.applications_plan, target_cpl = excluded.target_cpl,
          updated_at = excluded.updated_at;
    insert into public.an_vk_plan_changes (month, brand, city, previous_applications_plan,
      previous_target_cpl, applications_plan, target_cpl, changed_by, changed_by_id)
    values (v_month, v_brand, v_cities[i],
            case when v_had then v_prev.applications_plan end,
            case when v_had then v_prev.target_cpl end,
            v_apps[i], v_cpls[i], coalesce(v_by, ''), p_user);
    v_changed := v_changed + 1;
  end loop;
  return v_changed;
end;
$$;
revoke all on function public.an_vk_plans_save_month(text, text, jsonb, uuid) from public, anon, authenticated;

-- Сохранение планов: ручной план города (p_source 'manual', их
-- target-plans/update), импорт месяца ('single') или всех листов ('all').
-- p_months — [{month, plans: [{city, applications_plan, target_cpl}]}].
-- У них «все листы» сохранялись по месяцу — у нас все месяцы разом: ошибка в
-- одном не оставляет загруженными предыдущие.
create or replace function public.an_vk_plans_save(p_brand text, p_months jsonb, p_source text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  m jsonb;
  v_changed integer := 0;
  v_one integer;
  v_details text[] := '{}';
  v_count integer;
begin
  perform public.an_require_admin();
  if p_source not in ('manual', 'single', 'all') or p_months is null
     or jsonb_typeof(p_months) <> 'array' or jsonb_array_length(p_months) not between 1 and 24 then
    raise exception 'Неверный запрос' using errcode = '22023';
  end if;
  if p_source <> 'all' and jsonb_array_length(p_months) <> 1 then
    raise exception 'Неверный запрос' using errcode = '22023';
  end if;
  for m in select * from jsonb_array_elements(p_months) loop
    v_one := public.an_vk_plans_save_month(m->>'month', p_brand, m->'plans', v_uid);
    v_changed := v_changed + v_one;
    v_count := coalesce(jsonb_array_length(m->'plans'), 0);
    v_details := v_details || format('%s: %s', m->>'month', v_count);
    if p_source = 'manual' then
      perform public.an_audit_add(v_uid, 'target_plan_changed',
        format('%s: %s · %s', btrim(m->>'month'), p_brand, btrim(coalesce(m->'plans'->0->>'city', ''))));
    elsif p_source = 'single' then
      perform public.an_audit_add(v_uid, 'target_plans_imported',
        format('%s: %s из %s городов', btrim(m->>'month'), v_one, v_count));
    end if;
  end loop;
  if p_source = 'all' then
    perform public.an_audit_add(v_uid, 'target_plans_imported_all', array_to_string(v_details, ', '));
  end if;
  return jsonb_build_object('changed', v_changed, 'months', jsonb_array_length(p_months));
end;
$$;
revoke all on function public.an_vk_plans_save(text, jsonb, text) from public, anon;
grant execute on function public.an_vk_plans_save(text, jsonb, text) to authenticated;

-- Их remove_target_plan + target_plan_delete: true — удалён, false — уже нет.
create or replace function public.an_vk_plan_delete(p_month text, p_brand text, p_city text)
returns boolean
language plpgsql
security definer
set search_path = public
set extra_float_digits = 1
as $$
declare
  v_row public.an_vk_plans;
begin
  perform public.an_require_admin();
  if coalesce(p_month, '') !~ '^\d{4}-(0[1-9]|1[0-2])$' then
    raise exception 'Проверьте месяц.' using errcode = '22023';
  end if;
  if coalesce(p_brand, '') not in ('Lady Stretch', 'Lady Jump') or public.an_vk_strip(p_city) = '' then
    raise exception 'Проверьте бренд и город.' using errcode = '22023';
  end if;
  delete from public.an_vk_plans
   where month = p_month and brand = p_brand and city = public.an_vk_strip(p_city)
  returning * into v_row;
  if not found then
    return false;
  end if;
  perform public.an_audit_add(auth.uid(), 'target_plan_deleted', to_jsonb(v_row)::text);
  return true;
end;
$$;
revoke all on function public.an_vk_plan_delete(text, text, text) from public, anon;
grant execute on function public.an_vk_plan_delete(text, text, text) to authenticated;

