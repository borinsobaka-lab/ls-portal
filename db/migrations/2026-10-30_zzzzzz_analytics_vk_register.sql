create or replace function public.an_vk_ss_source_save(
  p_brand text, p_city text, p_leads_url text, p_applications_url text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_city text := public.an_vk_strip(public.an_vk_canonical_city(p_brand, p_city));
  v_leads text := public.an_vk_strip(p_leads_url);
  v_apps text := public.an_vk_strip(p_applications_url);
  v_brand text;
begin
  perform public.an_require_admin();
  v_brand := public.an_vk_check_brand(p_brand);
  if v_city = '' then
    raise exception 'Укажите город.' using errcode = '22023';
  end if;
  if char_length(v_city) > 120 then
    raise exception 'Название города слишком длинное.' using errcode = '22023';
  end if;
  if not public.an_vk_sheet_url_ok(v_leads) or char_length(v_leads) > 2000 then
    raise exception 'Укажите корректную ссылку Google Таблицы для лидов СС.' using errcode = '22023';
  end if;
  if not public.an_vk_sheet_url_ok(v_apps) or char_length(v_apps) > 2000 then
    raise exception 'Укажите корректную ссылку Google Таблицы для заявок СС.' using errcode = '22023';
  end if;
  insert into public.an_vk_ss_sources (brand, city, leads_sheet_url, applications_sheet_url)
  values (v_brand, v_city, v_leads, v_apps)
  on conflict (brand, city) do update
    set leads_sheet_url = excluded.leads_sheet_url, applications_sheet_url = excluded.applications_sheet_url,
        is_active = true, updated_at = now();
  perform public.an_audit_add(auth.uid(), 'community_message_source_saved',
    format('%s: %s', coalesce(p_brand, ''), coalesce(p_city, '')));
end;
$$;
