-- 5) Источники СС (администратору аналитики) -------------------------------------------

-- Их проверка ссылки: https, хост docs.google.com / www.docs.google.com,
-- в пути — /spreadsheets/ (как urlparse: схема без регистра, хост — как есть).
create or replace function public.an_vk_sheet_url_ok(p_url text)
returns boolean
language sql
immutable
as $$
  select coalesce((
    select m[1] in ('docs.google.com', 'www.docs.google.com') and position('/spreadsheets/' in m[2]) > 0
      from regexp_match(coalesce(p_url, ''), '^[Hh][Tt][Tt][Pp][Ss]://([^/?#]*)([^?#]*)') m), false)
$$;

