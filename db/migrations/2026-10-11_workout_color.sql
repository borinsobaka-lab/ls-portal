-- ============================================================================
-- Цвет тренировки (решение владельца 2026-10-11, STUDIO_FORMATS.md).
--
-- В пакетных студиях у тренировки нет типа (силовая/кардио/…) и иконки — есть
-- свой цвет: им окрашена полоска слева на карточке занятия в расписании.
-- Интенсивность (MET) там ставится вручную, без умолчания по типу.
--
-- Совместимо с подписочным форматом: новая колонка без умолчания, у
-- подписочных тренировок null — их цвет по-прежнему берётся из типа.
-- Идемпотентно. Выполняет мигратор при старте админки.
-- ============================================================================

alter table public.workouts
  add column if not exists color text;

alter table public.workouts
  drop constraint if exists workouts_color_hex;
alter table public.workouts
  add constraint workouts_color_hex
  check (color is null or color ~ '^#[0-9a-f]{6}$');

comment on column public.workouts.color is
  'Цвет тренировки #rrggbb (пакетный формат): полоска на карточке занятия в расписании. null — цвет по типу (подписочный формат).';

notify pgrst, 'reload schema';
