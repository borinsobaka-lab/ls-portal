-- §8.4): сбор лид-форм в Google-таблицы и счётчики заявок ЛФ для реестра.
--
-- Их lead_forms_collector.py и vk_ads.py: lead_collection_sources →
-- an_vk_lf_sources (таблица кабинета: Google-таблица, лист, старт сбора),
-- lead_submissions → an_vk_lf_submissions (заявка VK — зашифрованным JSON до
-- и после записи в таблицу, как у них; шифрует сервер портала,
-- ANALYTICS_SECRETS_KEY), lead_form_metric_leads → an_vk_lf_metric_leads
-- (какие заявки уже посчитаны в an_vk_lf_daily — счётчик не задваивается и
-- не уменьшается), google_drive_settings → an_google_settings.drive_* (папка;
-- OAuth-клиент и постоянный доступ Google Drive — в an_secrets, kind
-- 'google', ref 'drive'), google_drive_oauth_states → an_google_oauth_states.
--
-- Пишет сервер портала (service_role): сбор новых заявок — раз в 5 минут
-- (их lady-vk-ads-lead-forms.timer; запись в Google-таблицы — внешнее
-- действие, задача выключена, пока её не включат), счётчики текущего месяца —
-- раз в час (их lady-vk-ads-lead-forms-backfill.timer, только чтение VK).
-- Таблицы закрыты браузеру; администратору аналитики — RPC an_vk_lf_overview.
--
-- Идемпотентно. Выполняет мигратор при старте портала (db/migrate.ts).
-- ============================================================================

-- 1) Таблицы -------------------------------------------------------------------------

create table if not exists public.an_vk_lf_sources (
  account_id bigint primary key references public.an_vk_accounts(id) on delete cascade,
  spreadsheet_id text not null check (spreadsheet_id ~ '^[A-Za-z0-9_-]{1,200}$'),
  sheet_name text not null default 'Заявки' check (char_length(sheet_name) between 1 and 200),
  -- Заявки раньше старта в таблицу не попадают (их starts_at).
  starts_at timestamptz not null default now(),
  is_enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.an_vk_lf_submissions (
  id bigint generated by default as identity primary key,
  account_id bigint not null references public.an_vk_accounts(id) on delete cascade,
  vk_form_id text not null,
  vk_lead_id text not null,
  created_at_vk text not null default '',
  ad_plan_id text not null default '',
  ad_group_id text not null default '',
  banner_id text not null default '',
  encrypted_payload text not null,
  payload_sha256 text not null,
  received_at timestamptz not null default now(),
  sheet_status text not null default 'pending' check (sheet_status in ('pending', 'sent', 'error')),
  sheet_error text not null default '',
  sheet_sent_at timestamptz,
  unique (account_id, vk_lead_id)
);
create index if not exists an_vk_lf_submissions_pending
  on public.an_vk_lf_submissions (account_id, sheet_status, received_at, id);

create table if not exists public.an_vk_lf_metric_leads (
  account_id bigint not null references public.an_vk_accounts(id) on delete cascade,
  vk_lead_id text not null,
  stat_date date not null,
  primary key (account_id, vk_lead_id)
);
create index if not exists an_vk_lf_metric_leads_date on public.an_vk_lf_metric_leads (account_id, stat_date);

alter table public.an_google_settings add column if not exists drive_folder_id text not null default '';
alter table public.an_google_settings add column if not exists drive_updated_at timestamptz;
alter table public.an_google_settings add column if not exists drive_client_updated_at timestamptz;

create table if not exists public.an_google_oauth_states (
  state_hash text primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  expires_at timestamptz not null
);

alter table public.an_vk_lf_sources enable row level security;
alter table public.an_vk_lf_submissions enable row level security;
alter table public.an_vk_lf_metric_leads enable row level security;
alter table public.an_google_oauth_states enable row level security;
revoke all on public.an_vk_lf_sources, public.an_vk_lf_submissions, public.an_vk_lf_metric_leads,
  public.an_google_oauth_states from anon, authenticated;
grant all on public.an_vk_lf_sources, public.an_vk_lf_submissions, public.an_vk_lf_metric_leads,
  public.an_google_oauth_states to service_role;

-- 2) Сбор (сервер портала) --------------------------------------------------------------

-- Их _store_new_lead пачкой: новая заявка (повтор — пропуск); при
-- p_update_metrics — сразу в счётчик дня (дата заявки по МСК считает сервер,
-- без даты — не считается). Возвращает число новых.
create or replace function public.an_vk_lf_store(p_account bigint, p_leads jsonb, p_update_metrics boolean)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  l jsonb;
  v_new integer := 0;
  v_id bigint;
begin
  for l in select * from jsonb_array_elements(coalesce(p_leads, '[]')) loop
    insert into public.an_vk_lf_submissions (account_id, vk_form_id, vk_lead_id, created_at_vk, ad_plan_id,
      ad_group_id, banner_id, encrypted_payload, payload_sha256)
    values (p_account, l->>'form_id', l->>'lead_id', coalesce(l->>'created_at_vk', ''),
            coalesce(l->>'ad_plan_id', ''), coalesce(l->>'ad_group_id', ''), coalesce(l->>'banner_id', ''),
            l->>'encrypted_payload', l->>'payload_sha256')
    on conflict (account_id, vk_lead_id) do nothing
    returning id into v_id;
    if v_id is null then
      continue;
    end if;
    v_new := v_new + 1;
    v_id := null;
    if p_update_metrics and nullif(l->>'stat_date', '') is not null then
      insert into public.an_vk_lf_metric_leads (account_id, vk_lead_id, stat_date)
      values (p_account, l->>'lead_id', (l->>'stat_date')::date)
      on conflict do nothing;
      if found then
        insert into public.an_vk_lf_daily (account_id, stat_date, applications_count, updated_at)
        values (p_account, (l->>'stat_date')::date, 1, now())
        on conflict (account_id, stat_date) do update
          set applications_count = public.an_vk_lf_daily.applications_count + 1, updated_at = now();
      end if;
    end if;
  end loop;
  return v_new;
end;
$$;
revoke all on function public.an_vk_lf_store(bigint, jsonb, boolean) from public, anon, authenticated;
grant execute on function public.an_vk_lf_store(bigint, jsonb, boolean) to service_role;

-- Их merge_preserved_lf_metrics: известные заявки периода (из ответа VK и
-- сохранённые — p_leads [{lead_id, stat_date}]) добавляются к посчитанным,
-- счётчик дня — не меньше прежнего. Возвращает сумму за период.
create or replace function public.an_vk_lf_merge_metrics(p_account bigint, p_start date, p_end date, p_leads jsonb)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_sum bigint;
begin
  insert into public.an_vk_lf_metric_leads (account_id, vk_lead_id, stat_date)
  select distinct on (l->>'lead_id') p_account, l->>'lead_id', (l->>'stat_date')::date
    from jsonb_array_elements(coalesce(p_leads, '[]')) l
   where nullif(l->>'lead_id', '') is not null
     and (l->>'stat_date')::date between p_start and p_end
  on conflict do nothing;
  insert into public.an_vk_lf_daily (account_id, stat_date, applications_count, updated_at)
  select p_account, m.stat_date, count(*), now()
    from public.an_vk_lf_metric_leads m
   where m.account_id = p_account and m.stat_date between p_start and p_end
   group by m.stat_date
  on conflict (account_id, stat_date) do update
    set applications_count = greatest(public.an_vk_lf_daily.applications_count, excluded.applications_count),
        updated_at = excluded.updated_at;
  select coalesce(sum(applications_count), 0) into v_sum
    from public.an_vk_lf_daily where account_id = p_account and stat_date between p_start and p_end;
  return v_sum;
end;
$$;
revoke all on function public.an_vk_lf_merge_metrics(bigint, date, date, jsonb) from public, anon, authenticated;
grant execute on function public.an_vk_lf_merge_metrics(bigint, date, date, jsonb) to service_role;

-- 3) «Сбор лид-форм» (администратору аналитики) -----------------------------------------

-- Их lead_forms_page: подключение Google Drive, папка, активные кабинеты,
-- подключённые таблицы (+ сколько заявок записано, ждут записи, с ошибкой).
create or replace function public.an_vk_lf_overview()
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  perform public.an_require_admin();
  return jsonb_build_object(
    'drive', (select jsonb_build_object(
                'client', exists (select 1 from public.an_secrets
                                   where kind = 'google' and ref = 'drive' and name = 'oauth_client'),
                'connected', exists (select 1 from public.an_secrets
                                      where kind = 'google' and ref = 'drive' and name = 'refresh_token'),
                'folder_id', coalesce(g.drive_folder_id, ''),
                'updated_at', g.drive_updated_at)
                from (select 1) one left join public.an_google_settings g on g.id),
    'sheets_key', exists (select 1 from public.an_secrets
                           where kind = 'google' and ref = 'sheets' and name = 'service_account'),
    'active_accounts', (select count(*) from public.an_vk_accounts where is_active),
    -- Запись в таблицы (задача «vk_lf») — внешняя: без строки состояния выключена.
    'collector_enabled', coalesce((select enabled from public.an_job_state where job = 'vk_lf'), false),
    'collector_last', (select jsonb_build_object('at', last_finished_at, 'status', last_status,
                                                 'message', last_message)
                         from public.an_job_state where job = 'vk_lf'),
    'sources', coalesce((
      select jsonb_agg(jsonb_build_object(
               'account_id', s.account_id, 'name', a.name, 'city', a.city, 'is_active', a.is_active,
               'spreadsheet_id', s.spreadsheet_id, 'sheet_name', s.sheet_name, 'starts_at', s.starts_at,
               'is_enabled', s.is_enabled,
               'sent', coalesce(c.sent, 0), 'pending', coalesce(c.pending, 0), 'errors', coalesce(c.errors, 0),
               'last_error', c.last_error)
             order by a.city collate "C", a.name collate "C", a.id)
        from public.an_vk_lf_sources s
        join public.an_vk_accounts a on a.id = s.account_id
        left join lateral (
          select count(*) filter (where x.sheet_status = 'sent') as sent,
                 count(*) filter (where x.sheet_status = 'pending') as pending,
                 count(*) filter (where x.sheet_status = 'error') as errors,
                 max(x.sheet_error) filter (where x.sheet_status = 'error') as last_error
            from public.an_vk_lf_submissions x where x.account_id = s.account_id) c on true), '[]'));
end;
$$;
revoke all on function public.an_vk_lf_overview() from public, anon;
grant execute on function public.an_vk_lf_overview() to authenticated;
