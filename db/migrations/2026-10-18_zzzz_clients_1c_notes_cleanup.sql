-- ============================================================================
-- Заметки перенесённых из 1С клиентов — без служебных строк (решение
-- владельца 2026-10-18: что карточка из 1С, видно в столбце «Добавлен», в
-- заметке — только то, что реально нужно администратору).
--
-- Убирает из clients.notes перенесённых карточек (onec_ref не пуст) строки,
-- которые писал файл заливки первой версии: «Перенесено из 1С, статус — …»
-- и «Перенесено из 1С: карточки не было в отчёте клиентов …». Остальные
-- строки (сотрудник, комментарий 1С, телефоны, почта) и дописанное
-- сотрудниками остаются; заметка из одних служебных строк становится пустой.
-- Файл заливки второй версии этих строк не пишет, первую страница импорта не
-- принимает. Идемпотентно.
-- ============================================================================

update public.clients c
   set notes = nullif(btrim(array_to_string(array(
         select l.line
           from unnest(string_to_array(c.notes, E'\n')) with ordinality as l(line, n)
          where l.line not like 'Перенесено из 1С%'
          order by l.n
       ), E'\n')), '')
 where c.onec_ref is not null
   and c.notes like '%Перенесено из 1С%';
