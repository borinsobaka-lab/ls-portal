-- §8.4): «Контроль бюджетов» — прогноз остатка кабинетов, рекомендации по
-- пополнению и уведомления партнёрам в Telegram.
--
-- Их vk_ads.py: budget_alert_settings → an_vk_budget_settings,
-- budget_alerts → an_vk_budget_alerts, telegram_bot_settings →
-- an_tg_settings (токен бота и секрет Cloudflare-шлюза — an_secrets, kind
-- 'telegram', ref 'bot'; шифрует сервер портала), partner_notification_channels
-- → an_vk_partner_channels, budget_alert_deliveries → an_vk_budget_deliveries.
-- Числа предупреждений — numeric (их Decimal; считает сервер портала с их
-- точностью).
--
-- Предупреждения пересчитывает сервер (service_role): после сбора VK Ads и
-- при открытии страницы (их evaluate_budget_alerts); отправка в Telegram —
-- отдельная задача (их dispatch_budget_alerts; внешнее действие — выключена,
-- пока её не включат). Таблицы закрыты браузеру; серверу — RPC
-- an_vk_budget_inputs, an_vk_budget_apply, an_vk_budget_pending;
-- администратору аналитики — an_vk_budget_overview и
-- an_vk_partner_channel_delete.
--
-- Идемпотентно. Выполняет мигратор при старте портала (db/migrate.ts).
-- ============================================================================

-- 1) Таблицы -------------------------------------------------------------------------

create table if not exists public.an_vk_budget_settings (
  id boolean primary key default true check (id),
  is_enabled boolean not null default true,
  -- Их TEXT: пороги в днях — десятичные строки ('3', '1').
  warning_days text not null default '3' check (warning_days ~ '^\d+(\.\d+)?$'),
  critical_days text not null default '1' check (critical_days ~ '^\d+(\.\d+)?$'),
  target_days integer not null default 7 check (target_days between 1 and 365),
  updated_at timestamptz not null default now()
);
insert into public.an_vk_budget_settings (id) values (true) on conflict (id) do nothing;

create table if not exists public.an_vk_budget_alerts (
  id bigint generated by default as identity primary key,
  account_id bigint not null references public.an_vk_accounts(id) on delete cascade,
  stage text not null check (stage in ('warning', 'critical', 'zero')),
  balance numeric not null,
  average_daily_spend numeric not null,
  forecast_days numeric not null,
  recommended_topup numeric not null,
  period_start date not null,
  period_end date not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  resolved_at timestamptz
);
create index if not exists an_vk_budget_alerts_active
  on public.an_vk_budget_alerts (is_active, account_id, created_at desc);

create table if not exists public.an_tg_settings (
  id boolean primary key default true check (id),
  bot_username text not null default '' check (char_length(bot_username) <= 100),
  test_chat_id text not null default '' check (test_chat_id ~ '^(-?\d{1,31})?$'),
  gateway_url text not null default '' check (char_length(gateway_url) <= 500),
  last_test_at timestamptz,
  last_test_status text not null default '',
  updated_at timestamptz not null default now()
);
insert into public.an_tg_settings (id) values (true) on conflict (id) do nothing;

create table if not exists public.an_vk_partner_channels (
  id bigint generated by default as identity primary key,
  partner_name text not null unique check (char_length(partner_name) between 1 and 200),
  chat_id text not null check (chat_id ~ '^-?\d{1,31}$'),
  chat_title text not null default '' check (char_length(chat_title) <= 200),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.an_vk_budget_deliveries (
  id bigint generated by default as identity primary key,
  alert_id bigint not null references public.an_vk_budget_alerts(id) on delete cascade,
  channel_id bigint not null references public.an_vk_partner_channels(id) on delete cascade,
  status text not null check (status in ('sent', 'error')),
  details text not null default '',
  created_at timestamptz not null default now(),
  unique (alert_id, channel_id)
);

alter table public.an_vk_budget_settings enable row level security;
alter table public.an_vk_budget_alerts enable row level security;
alter table public.an_tg_settings enable row level security;
alter table public.an_vk_partner_channels enable row level security;
alter table public.an_vk_budget_deliveries enable row level security;
revoke all on public.an_vk_budget_settings, public.an_vk_budget_alerts, public.an_tg_settings,
  public.an_vk_partner_channels, public.an_vk_budget_deliveries from anon, authenticated;
grant all on public.an_vk_budget_settings, public.an_vk_budget_alerts, public.an_tg_settings,
  public.an_vk_partner_channels, public.an_vk_budget_deliveries to service_role;

-- 2) Входные данные прогноза (сервер портала) ---------------------------------------------

-- Их evaluate_budget_alerts: у каждого активного кабинета — последний остаток
-- и расход за 7 дней (сумма float, их CAST(spent AS REAL)) с числом дней со
-- статистикой.
create or replace function public.an_vk_budget_inputs(p_start date, p_end date)
returns table (account_id bigint, balance text, spent double precision, days bigint)
language sql
stable
security definer
set search_path = public
set extra_float_digits = 1
as $$
  select a.id,
         (select b.balance::text from public.an_vk_balances b
           where b.account_id = a.id order by b.measured_at desc, b.id desc limit 1),
         coalesce(s.spent, 0), coalesce(s.days, 0)
    from public.an_vk_accounts a
    left join lateral (
      select sum(d.spent::float8) as spent, count(distinct d.stat_date) as days
        from public.an_vk_daily_stats d
       where d.account_id = a.id and d.stat_date between p_start and p_end) s on true
   where a.is_active
   order by a.id
$$;
revoke all on function public.an_vk_budget_inputs(date, date) from public, anon, authenticated;
grant execute on function public.an_vk_budget_inputs(date, date) to service_role;

-- Их evaluate_budget_alerts, запись: вердикт по кабинету считает сервер
-- (p_rows [{account_id, kind no_spend|ok|alert, stage, balance, average,
-- forecast, recommended}]). no_spend — снять все (не считаются), ok — снять
-- все, alert — снять другие уровни и завести этот, если активного нет. Одна
-- транзакция под блокировкой: пересчёт со страницы и после сбора не
-- задваивает предупреждение.
create or replace function public.an_vk_budget_apply(p_start date, p_end date, p_rows jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  r jsonb;
  v_account bigint;
  v_stage text;
  v_n integer;
  v_created integer := 0;
  v_resolved integer := 0;
begin
  perform pg_advisory_xact_lock(hashtext('an_vk_budget_alerts'));
  for r in select * from jsonb_array_elements(coalesce(p_rows, '[]')) loop
    v_account := (r->>'account_id')::bigint;
    v_stage := r->>'stage';
    if r->>'kind' = 'no_spend' then
      update public.an_vk_budget_alerts set is_active = false, resolved_at = now()
       where account_id = v_account and is_active;
    elsif r->>'kind' = 'ok' then
      update public.an_vk_budget_alerts set is_active = false, resolved_at = now()
       where account_id = v_account and is_active;
      get diagnostics v_n = row_count;
      v_resolved := v_resolved + v_n;
    elsif r->>'kind' = 'alert' then
      update public.an_vk_budget_alerts set is_active = false, resolved_at = now()
       where account_id = v_account and is_active and stage <> v_stage;
      get diagnostics v_n = row_count;
      v_resolved := v_resolved + v_n;
      if not exists (select 1 from public.an_vk_budget_alerts
                      where account_id = v_account and stage = v_stage and is_active)
         and exists (select 1 from public.an_vk_accounts where id = v_account) then
        insert into public.an_vk_budget_alerts (account_id, stage, balance, average_daily_spend, forecast_days,
          recommended_topup, period_start, period_end)
        values (v_account, v_stage, (r->>'balance')::numeric, (r->>'average')::numeric,
                (r->>'forecast')::numeric, (r->>'recommended')::numeric, p_start, p_end);
        v_created := v_created + 1;
      end if;
    end if;
  end loop;
  return jsonb_build_object('created', v_created, 'resolved', v_resolved);
end;
$$;
revoke all on function public.an_vk_budget_apply(date, date, jsonb) from public, anon, authenticated;
grant execute on function public.an_vk_budget_apply(date, date, jsonb) to service_role;

-- Их dispatch_budget_alerts, выборка: активные предупреждения × активный чат
-- партнёра кабинета, ещё не отправленные в этот чат (старые — первыми).
create or replace function public.an_vk_budget_pending()
returns table (alert_id bigint, stage text, balance text, average_daily_spend text, forecast_days text,
               recommended_topup text, name text, city text, partner_name text, channel_id bigint, chat_id text)
language sql
stable
security definer
set search_path = public
as $$
  select b.id, b.stage, b.balance::text, b.average_daily_spend::text, b.forecast_days::text,
         b.recommended_topup::text, a.name, a.city, a.partner_name, c.id, c.chat_id
    from public.an_vk_budget_alerts b
    join public.an_vk_accounts a on a.id = b.account_id
    join public.an_vk_partner_channels c on c.partner_name = a.partner_name and c.is_active
    left join public.an_vk_budget_deliveries d on d.alert_id = b.id and d.channel_id = c.id
   where b.is_active and d.id is null
   order by b.created_at, b.id
$$;
revoke all on function public.an_vk_budget_pending() from public, anon, authenticated;
grant execute on function public.an_vk_budget_pending() to service_role;

-- 3) «Контроль бюджетов» (администратору аналитики) --------------------------------------

-- Их vk_ads_alerts_page: пороги, Telegram (без токена и секрета — только
-- «сохранён»), чаты партнёров, партнёры кабинетов, активные предупреждения
-- (сначала «исчерпан», затем «критический»; новые выше).
create or replace function public.an_vk_budget_overview()
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  perform public.an_require_admin();
  return jsonb_build_object(
    'settings', (select jsonb_build_object('is_enabled', s.is_enabled, 'warning_days', s.warning_days,
                                           'critical_days', s.critical_days, 'target_days', s.target_days)
                   from public.an_vk_budget_settings s where s.id),
    'telegram', (select jsonb_build_object(
                   'bot_username', t.bot_username, 'test_chat_id', t.test_chat_id,
                   'gateway_url', t.gateway_url, 'last_test_at', t.last_test_at,
                   'last_test_status', t.last_test_status,
                   'token_saved', exists (select 1 from public.an_secrets
                                           where kind = 'telegram' and ref = 'bot' and name = 'token'),
                   'gateway_secret_saved', exists (select 1 from public.an_secrets
                                                    where kind = 'telegram' and ref = 'bot'
                                                      and name = 'gateway_secret'))
                   from public.an_tg_settings t where t.id),
    'delivery_enabled', coalesce((select enabled from public.an_job_state where job = 'vk_budget_tg'), false),
    'channels', coalesce((
      select jsonb_agg(jsonb_build_object('id', c.id, 'partner_name', c.partner_name, 'chat_id', c.chat_id,
                                          'chat_title', c.chat_title, 'is_active', c.is_active)
             order by c.partner_name collate "C")
        from public.an_vk_partner_channels c), '[]'),
    'partners', coalesce((
      select jsonb_agg(p order by p collate "C")
        from (select distinct partner_name as p from public.an_vk_accounts where partner_name <> '') x), '[]'),
    'alerts', coalesce((
      select jsonb_agg(jsonb_build_object(
               'id', b.id, 'account_id', b.account_id, 'name', a.name, 'vk_account_id', a.vk_account_id,
               'city', a.city, 'partner_name', a.partner_name, 'stage', b.stage,
               'balance', b.balance::text, 'average_daily_spend', b.average_daily_spend::text,
               'forecast_days', b.forecast_days::text, 'recommended_topup', b.recommended_topup::text,
               'created_at', b.created_at,
               'delivery', (select jsonb_build_object('status', d.status, 'details', d.details, 'at', d.created_at)
                              from public.an_vk_budget_deliveries d where d.alert_id = b.id
                             order by d.id desc limit 1))
             order by case b.stage when 'zero' then 1 when 'critical' then 2 else 3 end, b.created_at desc, b.id desc)
        from public.an_vk_budget_alerts b
        join public.an_vk_accounts a on a.id = b.account_id
       where b.is_active), '[]'));
end;
$$;
revoke all on function public.an_vk_budget_overview() from public, anon;
grant execute on function public.an_vk_budget_overview() to authenticated;

-- Их delete_partner_notification_channel.
create or replace function public.an_vk_partner_channel_delete(p_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  perform public.an_require_admin();
  delete from public.an_vk_partner_channels where id = p_id;
  if not found then
    raise exception 'Привязка чата не найдена.' using errcode = 'P0002';
  end if;
  perform public.an_audit_add(auth.uid(), 'vk_ads_partner_notification_channel_deleted', p_id::text);
end;
$$;
revoke all on function public.an_vk_partner_channel_delete(bigint) from public, anon;
grant execute on function public.an_vk_partner_channel_delete(bigint) to authenticated;
